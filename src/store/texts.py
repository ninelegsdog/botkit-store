def order_review(order_id: int, product_name: str, price: object) -> str:
    """Экран оплаты: что именно покупается и за сколько, до списания Stars."""
    return f"📦 Заказ #{order_id}\nТовар: {product_name}\nСумма: {price} Stars\n\nОплата через Telegram Stars."


def orders_total(total: object) -> str:
    """Итог корзины перед оформлением."""
    return f"\n💰 Итого: {total} Stars"


def cart_line(name: str, qty: int, price: object) -> str:
    """Строка позиции в корзине: имя, количество, цена."""
    return f"• {name} x{qty} = {price} Stars"


def order_placed(orders_line: str, total: object, hint: str) -> str:
    """Подтверждение оформления: какие заказы, на какую сумму, что дальше."""
    return f"✅ Заказ оформлен: {orders_line}\nСумма: {total} Stars\n\n{hint}"


def delivery_payload(payload: str) -> str:
    """Выдача оплаченного товара."""
    return f"📥 Ваш товар:\n{payload}"


def orders_stats(day_paid: int, day_pending: int, week_paid: int, week_pending: int) -> str:
    """Статистика продаж за день и неделю."""
    return (
        f"📦 Статистика заказов:\n\nСегодня:\n"
        f"  Оплачено: {day_paid}\n"
        f"  Ожидает: {day_pending}\n\n"
        f"За неделю:\n"
        f"  Оплачено: {week_paid}\n"
        f"  Ожидает: {week_pending}"
    )
